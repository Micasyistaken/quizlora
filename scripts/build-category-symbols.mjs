assert.deepEqual(unknownNames, [], `Katalog dışı motif: ${unknownNames.join(', ')}`);
assert.deepEqual(missingExports, [], `Bulunamayan MDI simgeleri: ${missingExports.map(([name, icon]) => `${name}: ${icon}`).join(', ')}`);

