const categoryNames = tree.flatMap(([main, , , children]) => [main, ...children]);
const missingNames = categoryNames.filter(name => !symbols[name]);
const unknownNames = Object.keys(symbols).filter(name => !categoryNames.includes(name));
const missingExports = Object.entries(symbols).filter(([, icon]) => !mdi[icon]);
